//! Personal access tokens.
//!
//! Format: `skp_` + 40 lowercase hex chars (160 random bits) + `_` + a 6-char
//! base62 CRC-32 checksum of everything before the final `_`. The fixed prefix
//! and checksum let secret scanners find tokens with few false positives, and
//! let the server reject typos without a database lookup. Only the SHA-256
//! hash ([`hash_token`]) is stored.

use rand::RngCore;
use rand::rngs::OsRng;
use sha2::{Digest, Sha256};

/// Fixed token prefix.
pub const PREFIX: &str = "skp_";
/// Number of random bytes in a token (hex-encoded to 40 chars).
const RANDOM_BYTES: usize = 20;
const BODY_LEN: usize = RANDOM_BYTES * 2;
const CHECKSUM_LEN: usize = 6;
/// Total token length.
pub const TOKEN_LEN: usize = PREFIX.len() + BODY_LEN + 1 + CHECKSUM_LEN;
/// Number of body chars shown by [`prefix`].
const DISPLAY_LEN: usize = 8;

const CRC32: crc::Crc<u32> = crc::Crc::<u32>::new(&crc::CRC_32_ISO_HDLC);
const BASE62: &[u8; 62] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";

/// Why a string is not a well-formed access token.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum TokenError {
    /// Wrong prefix, length or character set.
    #[error("malformed access token")]
    Malformed,
    /// Well-formed but the checksum does not match (typo or forgery).
    #[error("access token checksum mismatch")]
    BadChecksum,
}

/// Generates a new token. Returns the plaintext (show it to the user once) and
/// its SHA-256 hash (store this).
pub fn generate() -> (String, [u8; 32]) {
    generate_with_prefix(PREFIX)
}

/// Generates a token in the same format with another 4-character `prefix` (OAuth tokens use
/// `sko_` and `skr_`, so they are never mistaken for personal access tokens).
pub fn generate_with_prefix(prefix: &str) -> (String, [u8; 32]) {
    debug_assert_eq!(prefix.len(), PREFIX.len());
    let mut random = [0u8; RANDOM_BYTES];
    OsRng.fill_bytes(&mut random);
    let mut token = String::with_capacity(TOKEN_LEN);
    token.push_str(prefix);
    token.push_str(&hex::encode(random));
    let checksum = checksum(&token);
    token.push('_');
    token.push_str(&checksum);
    let hash = hash_token(&token);
    (token, hash)
}

/// Checks the format and checksum; returns the 40-char random body on success.
pub fn parse(token: &str) -> Result<&str, TokenError> {
    parse_with_prefix(token, PREFIX)
}

/// [`parse`] for a token generated by [`generate_with_prefix`] with `prefix`.
pub fn parse_with_prefix<'a>(token: &'a str, prefix: &str) -> Result<&'a str, TokenError> {
    if token.len() != prefix.len() + BODY_LEN + 1 + CHECKSUM_LEN || !token.starts_with(prefix) {
        return Err(TokenError::Malformed);
    }
    let (head, sum) = token.split_at(prefix.len() + BODY_LEN);
    let body = &head[prefix.len()..];
    let sum = sum.strip_prefix('_').ok_or(TokenError::Malformed)?;
    if !body.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
        || !sum.bytes().all(|b| b.is_ascii_alphanumeric())
    {
        return Err(TokenError::Malformed);
    }
    if !crate::constant_time_eq(checksum(head).as_bytes(), sum.as_bytes()) {
        return Err(TokenError::BadChecksum);
    }
    Ok(body)
}

/// True when `token` is well formed and its checksum matches.
pub fn validate_checksum(token: &str) -> bool {
    parse(token).is_ok()
}

/// SHA-256 of the full token string; the value stored in the database.
pub fn hash_token(token: &str) -> [u8; 32] {
    Sha256::digest(token.as_bytes()).into()
}

/// A short, non-secret identifier for display: the first 8 chars after `skp_`.
/// Returns `None` if `token` does not start with the prefix or is too short.
pub fn prefix(token: &str) -> Option<&str> {
    token
        .strip_prefix(PREFIX)
        .and_then(|rest| rest.get(..DISPLAY_LEN))
}

/// Base62 encoding of the CRC-32 of `head`, left-padded to 6 chars.
fn checksum(head: &str) -> String {
    let mut n = CRC32.checksum(head.as_bytes());
    let mut out = [b'0'; CHECKSUM_LEN];
    for slot in out.iter_mut().rev() {
        *slot = BASE62[(n % 62) as usize];
        n /= 62;
    }
    out.iter().map(|&b| char::from(b)).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_tokens_validate() {
        let (token, hash) = generate();
        assert_eq!(token.len(), TOKEN_LEN);
        assert!(token.starts_with("skp_"));
        assert_eq!(hash, hash_token(&token));
        let body = parse(&token).expect("valid");
        assert_eq!(body.len(), 40);
        assert!(validate_checksum(&token));
        assert_eq!(prefix(&token), Some(&token[4..12]));
        let (other, _) = generate();
        assert_ne!(token, other);
    }

    #[test]
    fn prefixed_tokens() {
        let (token, hash) = generate_with_prefix("sko_");
        assert!(token.starts_with("sko_"));
        assert_eq!(hash, hash_token(&token));
        assert!(parse_with_prefix(&token, "sko_").is_ok());
        assert_eq!(parse(&token), Err(TokenError::Malformed));
        assert_eq!(
            parse_with_prefix(&token, "skr_"),
            Err(TokenError::Malformed)
        );
        let (pat, _) = generate();
        assert_eq!(parse_with_prefix(&pat, "sko_"), Err(TokenError::Malformed));
    }

    #[test]
    fn modified_tokens_are_rejected() {
        let (token, _) = generate();
        for (i, c) in token.char_indices().skip(PREFIX.len()) {
            if c == '_' {
                continue;
            }
            let replacement = if c == 'a' { "b" } else { "a" };
            let mut bad = token.clone();
            bad.replace_range(i..=i, replacement);
            assert!(!validate_checksum(&bad), "modified at {i}: {bad}");
        }
        assert_eq!(parse(&token[1..]), Err(TokenError::Malformed));
        assert_eq!(parse(&format!("{token}x")), Err(TokenError::Malformed));
        assert_eq!(parse(&token.to_uppercase()), Err(TokenError::Malformed));
        assert_eq!(parse(""), Err(TokenError::Malformed));
    }

    #[test]
    fn checksum_is_stable() {
        // CRC-32/ISO-HDLC("123456789") = 0xCBF43926 = 3421780262.
        let mut n: u32 = 0xCBF4_3926;
        let mut expect = Vec::new();
        while n > 0 {
            expect.push(BASE62[(n % 62) as usize]);
            n /= 62;
        }
        expect.reverse();
        let expect = String::from_utf8(expect).expect("ascii");
        assert_eq!(checksum("123456789"), format!("{expect:0>6}"));
    }

    #[test]
    fn prefix_handles_garbage() {
        assert_eq!(prefix("nope"), None);
        assert_eq!(prefix("skp_abc"), None);
    }
}
