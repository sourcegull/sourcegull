//! The language table. Written for Sourcegull; GitHub Linguist's
//! `languages.yml` was consulted for display names and common extensions.
//!
//! Order matters only for extensions listed under several languages: the
//! first entry is the default when content heuristics do not decide.

use crate::{Language, LanguageKind as K};

const fn l(
    id: &'static str,
    name: &'static str,
    kind: K,
    extensions: &'static [&'static str],
    filenames: &'static [&'static str],
    interpreters: &'static [&'static str],
) -> Language {
    Language {
        id,
        name,
        kind,
        extensions,
        filenames,
        interpreters,
    }
}

